"""Build a self-contained HTML summary report for one session.

HTML needs no extra library and prints to PDF from any browser (Ctrl+P).
"""
import html
from datetime import datetime

import pandas as pd

from config import SOURCE_REAL, SOURCE_SYNTHETIC

LIMITATIONS = [
    "No sensor has been calibrated against a reference instrument. Values are indicative.",
    "Current comes from an ACS712-5A read by the ESP32 ADC: absolute value only, zero "
    "offset taken at power-up, noise comparable to a small motor's current.",
    "The gas reading is a raw MQ-5 ADC value, not a concentration, and needs warm-up time.",
    "Gas, light and distance readings describe the surroundings. They are not motor-health measurements.",
    "Vibration is measured up to 250 Hz at most (500 Hz sampling) and depends on how the sensor is mounted.",
    "Motor speed and load are not measured.",
    "An alert or anomaly score means 'unusual compared with the baseline or training data'. "
    "It does not identify a failed component.",
    "The software does not predict a failure date or remaining useful life.",
    "Detection performance on real faults has not been measured.",
]

_STYLE = """
body{font-family:Segoe UI,Arial,sans-serif;margin:32px;color:#1c1c1c;max-width:1000px}
h1{margin-bottom:4px} h2{margin-top:28px;border-bottom:1px solid #bbb;padding-bottom:4px}
table{border-collapse:collapse;font-size:13px;margin:8px 0;display:block;overflow-x:auto}
th,td{border:1px solid #ccc;padding:4px 8px;text-align:left} th{background:#f0f0f0}
.banner{padding:10px 14px;font-weight:600;margin:12px 0;border:2px solid}
.synthetic{background:#fff4cc;border-color:#b58900}.real{background:#e2f4e5;border-color:#2e7d32}
.unknown{background:#fde0e0;border-color:#b71c1c} .muted{color:#555;font-size:13px}
"""


def _table(df, index=True):
    if df is None or len(df) == 0:
        return "<p class='muted'>None.</p>"
    return df.to_html(index=index, na_rep="–", float_format=lambda v: f"{v:.4g}", border=0)


def build_report_html(*, session, status, quality, timing, statistics, burst_features,
                      alerts, model_meta, ai_message, notes):
    """All arguments are the tables/dicts already shown in the dashboard."""
    source = session["data_source"]
    if source == SOURCE_SYNTHETIC:
        banner = ("synthetic", "SYNTHETIC DEMO DATA — generated by software. "
                               "Nothing in this report describes a real motor.")
    elif source == SOURCE_REAL:
        banner = ("real", "Real hardware recording. Sensors uncalibrated; see limitations.")
    else:
        banner = ("unknown", f"Data source: {source}. Origin unknown or mixed.")

    parts = [f"<html><head><meta charset='utf-8'><title>Session report {html.escape(str(session['session_id']))}</title>"
             f"<style>{_STYLE}</style></head><body>",
             "<h1>Motor condition monitoring — session report</h1>",
             f"<p class='muted'>Generated {datetime.now():%Y-%m-%d %H:%M}</p>",
             f"<div class='banner {banner[0]}'>{banner[1]}</div>",
             "<h2>Session</h2>",
             _table(pd.DataFrame({"value": {k: str(v) for k, v in session.items()}})),
             "<h2>Sensor status</h2>", _table(status),
             "<h2>Data quality</h2>",
             "<p class='muted'>Counts of readings per sensor. Problems here point to a sensor, "
             "wiring or communication issue, not to the motor.</p>",
             _table(quality),
             _table(pd.DataFrame({"value": {k: str(v) for k, v in timing.items()}})),
             "<h2>Statistics (valid readings only)</h2>", _table(statistics),
             "<h2>Vibration analysis</h2>"]
    if burst_features is None or len(burst_features) == 0:
        parts.append("<p class='muted'>No raw acceleration bursts in this session, so RMS and "
                     "frequency analysis were not possible.</p>")
    else:
        good = burst_features[burst_features["valid"].astype(bool)]
        cols = ["rms_total_g", "peak_g", "crest_factor", "dominant_freq_hz", "sample_rate_hz"]
        parts.append(f"<p>{len(good)} valid bursts of {len(burst_features)}. Gravity removed by "
                     "subtracting each axis's mean within a burst.</p>")
        parts.append(_table(good[cols].describe().loc[["min", "50%", "max"]]
                            .rename(index={"50%": "median"})))
    parts.append("<h2>Alerts</h2>")
    shown = alerts[["timestamp", "alert_type", "signal", "severity", "explanation",
                    "acknowledged", "resolution", "operator_note"]] if len(alerts) else alerts
    parts.append(_table(shown, index=False))
    parts.append("<h2>AI model</h2>")
    if model_meta:
        keep = ["model_version", "trained_at", "data_source", "training_id", "operating_notes",
                "features", "n_windows", "threshold", "config", "warnings", "evaluation"]
        parts.append(_table(pd.DataFrame({"value": {k: str(model_meta.get(k)) for k in keep}})))
    parts.append(f"<p>{html.escape(ai_message)}</p>")
    parts.append("<h2>Maintenance notes</h2>")
    parts.append("<p class='muted'>Operator observations. Only notes marked as a confirmed "
                 "diagnosis are verified.</p>")
    parts.append(_table(notes[["created_at", "kind", "text", "confirmed_diagnosis"]]
                        if len(notes) else notes, index=False))
    parts.append("<h2>Important limitations</h2><ul>"
                 + "".join(f"<li>{html.escape(x)}</li>" for x in LIMITATIONS) + "</ul>")
    parts.append("</body></html>")
    return "\n".join(parts)
